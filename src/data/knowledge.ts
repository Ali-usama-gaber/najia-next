export const articleBySlug = (slug: string) => articles.find((a) => a.slug === slug);

// Reading time from the article's own words (~180 Arabic words a minute).
export function readMinutes(a: Article) {
  const text = [a.lead, ...a.sections.flatMap((s) => [s.heading, ...(s.paragraphs ?? []), ...(s.bullets ?? [])])].join(' ');
  return Math.max(2, Math.round(text.split(/\s+/).length / 180));
}

// «دقيقتان» / «٣ دقائق» / «١٢ دقيقة» — Arabic number agreement for the read time.
export function readLabel(a: Article) {
  const n = readMinutes(a);
  if (n === 2) return 'دقيقتان قراءة';
  const num = n.toLocaleString('ar-SA');
  return n <= 10 ? `${num} دقائق قراءة` : `${num} دقيقة قراءة`;
}

