export const impactForEvent = (eventSlug: string) => impactItems.filter((i) => i.event === eventSlug);
export const relatedTo = (item: ImpactItem) =>
  impactItems.filter(
    (i) => i.slug !== item.slug && ((item.event && i.event === item.event) || item.related?.includes(i.slug) || i.related?.includes(item.slug)),
  );
